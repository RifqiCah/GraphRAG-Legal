#!/usr/bin/env python3
"""
Rule-based QC for graph_v2.

This script audits the local graph output generated by
scripts/graph/build_graph_v2.py. It does not call an LLM and does not modify
graph files.

Outputs:
- outputs/reports/v2/graph_v2_qc_report.json
- outputs/reports/v2/graph_v2_qc_issues.csv
"""

from __future__ import annotations

import argparse
import csv
import json
from collections import Counter, defaultdict
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Dict, Iterable, List, Set, Tuple


DEFAULT_GRAPH_DIR = Path("indexes/graph_v2")
DEFAULT_SCHEMA_PATH = Path("ontology/v2/schema.json")
DEFAULT_REPORT_JSON = Path("outputs/reports/v2/graph_v2_qc_report.json")
DEFAULT_ISSUES_CSV = Path("outputs/reports/v2/graph_v2_qc_issues.csv")
EXPECTED_EXCLUDED = {"REG-UUD-1945"}


def read_json(path: Path) -> Dict[str, Any]:
    with path.open("r", encoding="utf-8") as f:
        return json.load(f)


def iter_jsonl(path: Path) -> Iterable[Dict[str, Any]]:
    with path.open("r", encoding="utf-8") as f:
        for line_no, line in enumerate(f, start=1):
            line = line.strip()
            if not line:
                continue
            row = json.loads(line)
            row["_line_no"] = line_no
            yield row


def write_json(path: Path, payload: Dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as f:
        json.dump(payload, f, ensure_ascii=False, indent=2)


def write_issues_csv(path: Path, issues: List[Dict[str, Any]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fields = [
        "severity",
        "issue_type",
        "detail",
        "node_id",
        "edge_id",
        "source_id",
        "predicate",
        "target_id",
        "source_type",
        "target_type",
        "line_no",
    ]
    with path.open("w", encoding="utf-8", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=fields)
        writer.writeheader()
        for issue in issues:
            writer.writerow({field: issue.get(field, "") for field in fields})


def issue(
    severity: str,
    issue_type: str,
    detail: str,
    *,
    node_id: str = "",
    edge_id: str = "",
    source_id: str = "",
    predicate: str = "",
    target_id: str = "",
    source_type: str = "",
    target_type: str = "",
    line_no: Any = "",
) -> Dict[str, Any]:
    return {
        "severity": severity,
        "issue_type": issue_type,
        "detail": detail,
        "node_id": node_id,
        "edge_id": edge_id,
        "source_id": source_id,
        "predicate": predicate,
        "target_id": target_id,
        "source_type": source_type,
        "target_type": target_type,
        "line_no": line_no,
    }


def as_set(value: Any) -> Set[str]:
    if isinstance(value, list):
        return set(value)
    if isinstance(value, str):
        return {value}
    return set()


def load_edge_constraints(schema_path: Path) -> Dict[str, Dict[str, Set[str]]]:
    schema = read_json(schema_path)
    constraints: Dict[str, Dict[str, Set[str]]] = {}
    for group in schema.get("edge_definitions", {}).values():
        if not isinstance(group, list):
            continue
        for row in group:
            label = row.get("label")
            if not label:
                continue
            constraints[label] = {
                "source_type": as_set(row.get("source_type")),
                "target_type": as_set(row.get("target_type")),
            }
    return constraints


def load_id_prefixes(schema_path: Path) -> Dict[str, str]:
    return read_json(schema_path).get("id_prefixes", {})


def edge_signature(edge: Dict[str, Any]) -> Tuple[str, str, str, str]:
    return (
        edge.get("source_id", ""),
        edge.get("predicate", ""),
        edge.get("target_id", ""),
        json.dumps(edge.get("properties", {}), ensure_ascii=False, sort_keys=True),
    )


def load_nodes(nodes_path: Path) -> Tuple[Dict[str, Dict[str, Any]], List[Dict[str, Any]]]:
    nodes: Dict[str, Dict[str, Any]] = {}
    issues: List[Dict[str, Any]] = []
    seen = set()

    for row in iter_jsonl(nodes_path):
        node_id = row.get("id", "")
        if not node_id:
            issues.append(issue("error", "empty_node_id", "Node id is empty", line_no=row.get("_line_no", "")))
            continue
        if node_id in seen:
            issues.append(issue("error", "duplicate_node_id", "Duplicate node id in nodes.jsonl", node_id=node_id, line_no=row.get("_line_no", "")))
            continue
        seen.add(node_id)
        nodes[node_id] = row

        if not row.get("type"):
            issues.append(issue("error", "empty_node_type", "Node type is empty", node_id=node_id, line_no=row.get("_line_no", "")))
        if row.get("type") != "Regulasi" and not row.get("is_stub") and not row.get("regulasi_id"):
            issues.append(issue("warning", "empty_regulasi_id", "Non-stub node has empty regulasi_id", node_id=node_id, line_no=row.get("_line_no", "")))

    return nodes, issues


def load_edges(edges_path: Path) -> Tuple[List[Dict[str, Any]], List[Dict[str, Any]]]:
    edges = []
    issues: List[Dict[str, Any]] = []
    seen_edge_ids = set()
    seen_keys = set()
    signatures = Counter()

    for row in iter_jsonl(edges_path):
        edge_id = row.get("id", "")
        if not edge_id:
            issues.append(issue("error", "empty_edge_id", "Edge id is empty", line_no=row.get("_line_no", "")))
        elif edge_id in seen_edge_ids:
            issues.append(issue("error", "duplicate_edge_id", "Duplicate edge id in edges.jsonl", edge_id=edge_id, line_no=row.get("_line_no", "")))
        seen_edge_ids.add(edge_id)

        key = row.get("key", "")
        if key:
            if key in seen_keys:
                issues.append(issue("error", "duplicate_edge_key", "Duplicate edge key in edges.jsonl", edge_id=edge_id, line_no=row.get("_line_no", "")))
            seen_keys.add(key)

        for field in ["source_id", "target_id", "predicate", "source_type", "target_type"]:
            if not row.get(field):
                issues.append(issue("error", f"empty_{field}", f"{field} is empty", edge_id=edge_id, line_no=row.get("_line_no", "")))

        signatures[edge_signature(row)] += 1
        edges.append(row)

    for sig, count in signatures.items():
        if count > 1:
            source_id, predicate, target_id, _ = sig
            issues.append(issue(
                "warning",
                "duplicate_edge_signature",
                f"Same source-predicate-target-properties appears {count} times",
                source_id=source_id,
                predicate=predicate,
                target_id=target_id,
            ))

    return edges, issues


def validate_prefixes(nodes: Dict[str, Dict[str, Any]], prefixes: Dict[str, str]) -> List[Dict[str, Any]]:
    issues = []
    for node_id, node in nodes.items():
        node_type = node.get("type", "")
        prefix = prefixes.get(node_type)
        if not prefix:
            continue
        if not node_id.startswith(prefix + "-"):
            # Current parser intentionally uses BAGIAN-/PARAGRAF- ids while
            # ontology reserves BGN-/PRG-. Keep this as warning, not blocker.
            issues.append(issue(
                "warning",
                "node_id_prefix_mismatch",
                f"{node_type} id should start with {prefix}- according to ontology",
                node_id=node_id,
                line_no=node.get("_line_no", ""),
            ))
    return issues


def validate_edges(
    nodes: Dict[str, Dict[str, Any]],
    edges: List[Dict[str, Any]],
    constraints: Dict[str, Dict[str, Set[str]]],
) -> List[Dict[str, Any]]:
    issues = []
    valid_predicates = set(constraints)

    for edge in edges:
        edge_id = edge.get("id", "")
        source_id = edge.get("source_id", "")
        target_id = edge.get("target_id", "")
        predicate = edge.get("predicate", "")
        source_type = edge.get("source_type", "")
        target_type = edge.get("target_type", "")
        line_no = edge.get("_line_no", "")

        source = nodes.get(source_id)
        target = nodes.get(target_id)
        if not source:
            issues.append(issue("error", "missing_source_node", "source_id not found in nodes", edge_id=edge_id, source_id=source_id, predicate=predicate, target_id=target_id, line_no=line_no))
        if not target:
            issues.append(issue("error", "missing_target_node", "target_id not found in nodes", edge_id=edge_id, source_id=source_id, predicate=predicate, target_id=target_id, line_no=line_no))

        if source and source_type and source.get("type") != source_type:
            issues.append(issue(
                "error",
                "edge_source_type_mismatch_node",
                f"edge source_type={source_type}, node type={source.get('type')}",
                edge_id=edge_id,
                source_id=source_id,
                predicate=predicate,
                target_id=target_id,
                source_type=source_type,
                target_type=target_type,
                line_no=line_no,
            ))
        if target and target_type and target.get("type") != target_type:
            issues.append(issue(
                "error",
                "edge_target_type_mismatch_node",
                f"edge target_type={target_type}, node type={target.get('type')}",
                edge_id=edge_id,
                source_id=source_id,
                predicate=predicate,
                target_id=target_id,
                source_type=source_type,
                target_type=target_type,
                line_no=line_no,
            ))

        if predicate not in valid_predicates:
            issues.append(issue("error", "unknown_predicate", predicate, edge_id=edge_id, source_id=source_id, predicate=predicate, target_id=target_id, line_no=line_no))
            continue

        allowed_source = constraints[predicate].get("source_type", set())
        allowed_target = constraints[predicate].get("target_type", set())
        if allowed_source and source_type not in allowed_source:
            issues.append(issue(
                "error",
                "source_type_not_allowed_for_predicate",
                f"{source_type} not in {sorted(allowed_source)}",
                edge_id=edge_id,
                source_id=source_id,
                predicate=predicate,
                target_id=target_id,
                source_type=source_type,
                target_type=target_type,
                line_no=line_no,
            ))
        if allowed_target and target_type not in allowed_target:
            issues.append(issue(
                "error",
                "target_type_not_allowed_for_predicate",
                f"{target_type} not in {sorted(allowed_target)}",
                edge_id=edge_id,
                source_id=source_id,
                predicate=predicate,
                target_id=target_id,
                source_type=source_type,
                target_type=target_type,
                line_no=line_no,
            ))

    return issues


def validate_graph_shape(nodes: Dict[str, Dict[str, Any]], edges: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    issues = []
    out_by_source_pred = defaultdict(list)
    in_by_target_pred = defaultdict(list)

    for edge in edges:
        out_by_source_pred[(edge.get("source_id", ""), edge.get("predicate", ""))].append(edge)
        in_by_target_pred[(edge.get("target_id", ""), edge.get("predicate", ""))].append(edge)

    for node_id, node in nodes.items():
        node_type = node.get("type")
        is_stub = bool(node.get("is_stub"))

        if node_type == "Regulasi" and not is_stub:
            has_direct_pasal = bool(out_by_source_pred.get((node_id, "MEMILIKI_PASAL")))
            has_bab = bool(out_by_source_pred.get((node_id, "MEMILIKI_BAB")))
            if not has_direct_pasal and not has_bab:
                issues.append(issue("warning", "regulasi_without_body_edge", "Regulasi has no MEMILIKI_PASAL or MEMILIKI_BAB edge", node_id=node_id, line_no=node.get("_line_no", "")))

        if node_type == "Chunk":
            if not in_by_target_pred.get((node_id, "MEMILIKI_CHUNK")):
                issues.append(issue("error", "orphan_chunk", "Chunk has no incoming MEMILIKI_CHUNK edge", node_id=node_id, line_no=node.get("_line_no", "")))
            source_node_id = (node.get("properties") or {}).get("source_node_id", "")
            if not source_node_id:
                issues.append(issue("error", "chunk_missing_source_node_id", "Chunk properties.source_node_id is empty", node_id=node_id, line_no=node.get("_line_no", "")))
            elif source_node_id not in nodes:
                issues.append(issue("error", "chunk_source_node_missing", "Chunk source_node_id not found in nodes", node_id=node_id, detail=f"Missing {source_node_id}", line_no=node.get("_line_no", "")))

        if node_type in {"Pasal", "Ayat", "SubItem", "Konsiderans", "Dasar_Hukum", "Penjelasan_Pasal"} and not is_stub:
            if node_type == "Pasal" and out_by_source_pred.get((node_id, "MEMILIKI_AYAT")):
                continue
            if not out_by_source_pred.get((node_id, "MEMILIKI_CHUNK")):
                issues.append(issue("warning", "source_node_without_chunk", f"{node_type} has no outgoing MEMILIKI_CHUNK edge", node_id=node_id, line_no=node.get("_line_no", "")))

    return issues


def summarize(nodes: Dict[str, Dict[str, Any]], edges: List[Dict[str, Any]], issues: List[Dict[str, Any]], summary_file: Dict[str, Any]) -> Dict[str, Any]:
    errors = [row for row in issues if row.get("severity") == "error"]
    warnings = [row for row in issues if row.get("severity") == "warning"]
    node_types = Counter(node.get("type", "Unknown") for node in nodes.values())
    edge_predicates = Counter(edge.get("predicate", "UNKNOWN") for edge in edges)
    edge_methods = Counter(edge.get("extraction_method", "unknown") for edge in edges)
    issue_types = Counter(row.get("issue_type", "") for row in issues)

    return {
        "schema_version": "2.0.0",
        "timestamp": datetime.now(timezone.utc).isoformat(),
        "graph_summary_created_at": summary_file.get("created_at", ""),
        "excluded_regulasi_ids": summary_file.get("excluded_regulasi_ids", []),
        "nodes_checked": len(nodes),
        "edges_checked": len(edges),
        "total_errors": len(errors),
        "total_warnings": len(warnings),
        "issues_by_type": dict(issue_types),
        "nodes_by_type": dict(node_types),
        "edges_by_predicate": dict(edge_predicates),
        "edges_by_extraction_method": dict(edge_methods),
        "status": "PASS" if not errors else "FAIL",
        "report_notes": [
            "Warnings are audit hints, not blockers.",
            "REG-UUD-1945 is expected to be excluded until the correct raw file is available.",
        ],
        "sample_issues": issues[:100],
    }


def audit(args: argparse.Namespace) -> Dict[str, Any]:
    graph_dir = args.graph_dir
    nodes_path = graph_dir / "nodes.jsonl"
    edges_path = graph_dir / "edges.jsonl"
    summary_path = graph_dir / "summary.json"

    issues: List[Dict[str, Any]] = []

    for path in [nodes_path, edges_path, summary_path]:
        if not path.exists():
            issues.append(issue("error", "missing_graph_file", str(path)))

    if issues:
        report = summarize({}, [], issues, {})
        write_json(args.report_json, report)
        write_issues_csv(args.issues_csv, issues)
        return report

    summary_file = read_json(summary_path)
    nodes, node_issues = load_nodes(nodes_path)
    edges, edge_issues = load_edges(edges_path)
    issues.extend(node_issues)
    issues.extend(edge_issues)

    excluded = set(summary_file.get("excluded_regulasi_ids", []))
    if not EXPECTED_EXCLUDED.issubset(excluded) and not args.allow_uud:
        issues.append(issue("error", "missing_expected_exclusion", "REG-UUD-1945 should be excluded by default"))

    constraints = load_edge_constraints(args.schema_path)
    prefixes = load_id_prefixes(args.schema_path)
    issues.extend(validate_edges(nodes, edges, constraints))
    if args.check_prefix:
        issues.extend(validate_prefixes(nodes, prefixes))
    issues.extend(validate_graph_shape(nodes, edges))

    report = summarize(nodes, edges, issues, summary_file)
    write_json(args.report_json, report)
    write_issues_csv(args.issues_csv, issues)
    return report


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Audit local graph_v2 output.")
    parser.add_argument("--graph-dir", type=Path, default=DEFAULT_GRAPH_DIR)
    parser.add_argument("--schema-path", type=Path, default=DEFAULT_SCHEMA_PATH)
    parser.add_argument("--report-json", type=Path, default=DEFAULT_REPORT_JSON)
    parser.add_argument("--issues-csv", type=Path, default=DEFAULT_ISSUES_CSV)
    parser.add_argument("--allow-uud", action="store_true", help="Do not require REG-UUD-1945 exclusion.")
    parser.add_argument("--check-prefix", action="store_true", help="Warn on ontology id_prefix mismatch.")
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    report = audit(args)
    print(f"status: {report['status']}")
    print(f"nodes_checked: {report['nodes_checked']}")
    print(f"edges_checked: {report['edges_checked']}")
    print(f"total_errors: {report['total_errors']}")
    print(f"total_warnings: {report['total_warnings']}")
    print(f"report_json: {args.report_json}")
    print(f"issues_csv: {args.issues_csv}")


if __name__ == "__main__":
    main()
